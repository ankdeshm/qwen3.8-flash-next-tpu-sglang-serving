#!/usr/bin/env python3
"""SGLang-TorchTPU single-host serving sweep on one TPU v7x host (4 chips = 8 TensorCore ranks).

For each server variant (TP/EP/DP-attention layout, weight precision, KV dtype, speculative decoding) this:
  1. writes an SGLang TPU launch recipe under benchmark/tpu/recipe/configs/rsi_custom/ (same base flags as the
     upstream validated recipes: _FP8_BASE_CONFIG + LIBTPU_FLAGS),
  2. starts `python -m benchmark.tpu.launch_server` with FORCE_SINGLE_HOST=1 and waits for /health_generate,
  3. runs deterministic smoke generation + few-shot GSM8K accuracy gate (`sglang.test.few_shot_gsm8k`),
  4. runs `python -m sglang.benchmark.serving` over a (input_len, output_len, concurrency) grid with fixed-length
     ShareGPT-sampled prompts (--dataset-name random --random-range-ratio 1.0, ignore-EOS so every request decodes
     exact output_len tokens),
  5. stops the server, and persists incremental summary.json / SUMMARY.md locally and to GCS.
"""
